<?php

namespace App\Http\Controllers\Admin\Service;

use App\Http\Controllers\Controller;
use App\Models\Service;
use App\Models\ServiceAddon;
use Illuminate\Http\Request;
use Illuminate\Support\Str;

class ServiceAddonController extends Controller
{
    public function index($serviceId)
    {
        $service = Service::with('addons')->findOrFail($serviceId);
        
        return view('admin.addons.index', compact('service'));
    }

    public function create($serviceId)
    {
        $service = Service::findOrFail($serviceId);
        $locales = config('app.available_locales');
        $localeNames = config('app.locale_names');
        $addonTypes = ServiceAddon::getAddonTypes();
        
        return view('admin.addons.create', compact('service', 'locales', 'localeNames', 'addonTypes'));
    }

    public function store(Request $request, $serviceId)
    {
        $service = Service::findOrFail($serviceId);
        
        // Build validation rules dynamically for all locales
        $rules = [
            'price' => 'required|numeric|min:0',
            'type' => 'required|in:one_time,monthly,annual,six_months,three_months',
            'payment_link' => 'nullable|url|max:2048',
        ];
        
        foreach (config('app.available_locales') as $locale) {
            $rules["name_{$locale}"] = 'required|string|max:255';
            $rules["description_{$locale}"] = 'nullable|string';
        }
        
        $validated = $request->validate($rules);
        
        // Build translations array
        $translations = [];
        foreach (config('app.available_locales') as $locale) {
            $translations['name'][$locale] = $validated["name_{$locale}"];
            $translations['description'][$locale] = $validated["description_{$locale}"] ?? '';
        }
        
        // Create addon (slug auto-generated by Laravel slug package)
        ServiceAddon::create([
            'service_id' => $service->id,
            'name' => $translations['name'],
            'description' => $translations['description'],
            'price' => $validated['price'],
            'type' => $validated['type'],
            'payment_link' => $validated['payment_link'] ?? null,
        ]);
        
        session()->flash('success', 'Addon created successfully!');
        
        return redirect()->route('admin.services.addons.index', $service->id);
    }

    public function edit($addonId)
    {
        $addon = ServiceAddon::with('service')->findOrFail($addonId);
        $locales = config('app.available_locales');
        $localeNames = config('app.locale_names');
        $addonTypes = ServiceAddon::getAddonTypes();
        
        return view('admin.addons.edit', compact('addon', 'locales', 'localeNames', 'addonTypes'));
    }

    public function update(Request $request, $addonId)
    {
        $addon = ServiceAddon::findOrFail($addonId);
        
        // Build validation rules dynamically for all locales
        $rules = [
            'price' => 'required|numeric|min:0',
            'type' => 'required|in:one_time,monthly,annual,six_months,three_months',
            'payment_link' => 'nullable|url|max:2048',
        ];
        
        foreach (config('app.available_locales') as $locale) {
            $rules["name_{$locale}"] = 'required|string|max:255';
            $rules["description_{$locale}"] = 'nullable|string';
        }
        
        $validated = $request->validate($rules);
        
        // Build translations array
        $translations = [];
        foreach (config('app.available_locales') as $locale) {
            $translations['name'][$locale] = $validated["name_{$locale}"];
            $translations['description'][$locale] = $validated["description_{$locale}"] ?? '';
        }
        
        // Update addon (slug auto-updated by Laravel slug package)
        $addon->update([
            'name' => $translations['name'],
            'description' => $translations['description'],
            'price' => $validated['price'],
            'type' => $validated['type'],
            'payment_link' => $validated['payment_link'] ?? null,
        ]);
        
        session()->flash('success', 'Addon updated successfully!');
        
        return redirect()->route('admin.services.addons.index', $addon->service_id);
    }

    public function destroy($addonId)
    {
        $addon = ServiceAddon::findOrFail($addonId);
        $serviceId = $addon->service_id;
        
        $addon->delete();
        
        session()->flash('success', 'Addon deleted successfully!');
        
        return redirect()->route('admin.services.addons.index', $serviceId);
    }
}

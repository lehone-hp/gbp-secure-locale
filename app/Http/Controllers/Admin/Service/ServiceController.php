<?php

namespace App\Http\Controllers\Admin\Service;

use App\Http\Controllers\Controller;
use App\Models\Service;
use Illuminate\Http\Request;
use Illuminate\Support\Str;

class ServiceController extends Controller
{
    public function index()
    {
        $services = Service::withCount('addons')
            ->orderBy('created_at', 'desc')
            ->paginate(20);

        return view('admin.services.index', compact('services'));
    }

    public function create()
    {
        $locales = config('app.available_locales');
        $localeNames = config('app.locale_names');
        
        return view('admin.services.create', compact('locales', 'localeNames'));
    }

    public function store(Request $request)
    {
        // Build validation rules dynamically for all locales
        $rules = [];
        
        foreach (config('app.available_locales') as $locale) {
            $rules["name_{$locale}"] = 'required|string|max:255';
            $rules["caption_{$locale}"] = 'required|string|max:500';
            $rules["description_{$locale}"] = 'required|string';
        }
        
        $rules['is_hidden'] = 'sometimes|boolean';

        $validated = $request->validate($rules);
        
        // Build translations array
        $translations = [];
        foreach (config('app.available_locales') as $locale) {
            $translations['name'][$locale] = $validated["name_{$locale}"];
            $translations['caption'][$locale] = $validated["caption_{$locale}"];
            $translations['description'][$locale] = $validated["description_{$locale}"];
        }
        
        // Create service (slug auto-generated by Laravel slug package)
        Service::create([
            'name' => $translations['name'],
            'caption' => $translations['caption'],
            'description' => $translations['description'],
            'is_hidden' => $request->boolean('is_hidden'),
        ]);
        
        session()->flash('success', __('messages.content_updated'));
        
        return redirect()->route('admin.services.index');
    }

    public function edit(Service $service)
    {
        $locales = config('app.available_locales');
        $localeNames = config('app.locale_names');
        
        return view('admin.services.edit', compact('service', 'locales', 'localeNames'));
    }

    public function update(Request $request, Service $service)
    {
        // Build validation rules dynamically for all locales
        $rules = [];
        
        foreach (config('app.available_locales') as $locale) {
            $rules["name_{$locale}"] = 'required|string|max:255';
            $rules["caption_{$locale}"] = 'required|string|max:500';
            $rules["description_{$locale}"] = 'required|string';
        }
        
        $rules['is_hidden'] = 'sometimes|boolean';

        $validated = $request->validate($rules);
        
        // Build translations array
        $translations = [];
        foreach (config('app.available_locales') as $locale) {
            $translations['name'][$locale] = $validated["name_{$locale}"];
            $translations['caption'][$locale] = $validated["caption_{$locale}"];
            $translations['description'][$locale] = $validated["description_{$locale}"];
        }
        
        // Update service (slug auto-updated by Laravel slug package)
        $service->update([
            'name' => $translations['name'],
            'caption' => $translations['caption'],
            'description' => $translations['description'],
            'is_hidden' => $request->boolean('is_hidden'),
        ]);
        
        session()->flash('success', __('messages.content_updated'));
        
        return redirect()->route('admin.services.index');
    }

    public function destroy(Service $service)
    {
        // Check if service has addons
        if ($service->addons()->count() > 0) {
            session()->flash('error', 'Cannot delete service with addons. Delete addons first.');
            return redirect()->back();
        }
        
        $service->delete();
        
        session()->flash('success', 'Service deleted successfully!');
        
        return redirect()->route('admin.services.index');
    }
}
